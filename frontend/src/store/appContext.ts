/**
 * A single tab open in the workspace shell.
 * These tabs represent the currently opened project, route, or database views.
 */
export interface WorkspaceTab {
  /** Unique tab id used for selection and lookup. */
  id: string;
  /** Human-readable label displayed in the tab bar. */
  label: string;
  /** Optional icon name for the tab. */
  icon?: string;
  /** Route or resource path associated with this tab. */
  path: string;
  /** Logical tab category such as env, database, or project. */
  category?: string;
  /** Whether the tab is read-only and cannot be edited. */
  isReadonly?: boolean;
  /** Query params passed when opening this route. */
  query?: LocationQuery;
}
