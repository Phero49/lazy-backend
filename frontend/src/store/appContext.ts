/**
 * Describes how request data is sourced and mapped into a field.
 */
export type Payload = {
  /** Where the value comes from in the request pipeline. */
  dataSource:
    | "body"
    | "form"
    | "param"
    | "query"
    | "header"
    | "injected values"
    | "-";
  /** Field name in the payload or database model. */
  fieldName: string;
  /** Runtime type the field should be treated as. */
  dataType: string;
  /** Whether the field is required before the route can run. */
  required: boolean;
};

/**
 * A query definition used for database operations, including select filters and output columns.
 */
export interface DatabaseQuery {
  /** Tables included in the query, optionally with a join definition. */
  tables: {
    /** Table name participating in the query. */
    table: string;
    /** Join definition for this table when it is linked to another table. */
    join?: Join;
  }[];

  /** Result columns selected by the query. */
  columns: {
    /** Column name from the database table. */
    column: string;
    /** Optional alias used in the result set. */
    alias?: string;
    /** Optional attributes or function wrappers for this column. */
    attributes?: {
      /** Attribute name such as count, max, or aggregate metadata. */
      name: string;
      /** True when the attribute is a function call rather than a plain value. */
      isFunction: boolean;
      /** Values passed into this attribute or function. */
      values: {
        /** Whether the value is sourced from a column or a static literal. */
        source: "column" | "static";
        /** Optional table name when the source is a column. */
        table?: string;
        /** Value payload associated with this attribute item. */
        value: string;
      }[];
    }[];
  }[];
  /** Filter conditions applied to the query. */
  where: Condition[];
}

/**
 * A database action block configured by the backend or UI builder.
 */
export interface DatabaseOperations {
  /** Friendly name of the operation. */
  name: string;
  /** Optional expression or condition string used by this operation. */
  conditions?: string;
  /** Type of database action being executed. */
  databaseAction: "SELECT" | "UPDATE" | "DELETE" | "INSERT";
  /** Structured query definition for the operation. */
  query: DatabaseQuery;
}

/**
 * A dependency call block that references an installed dependency and its arguments.
 */
export interface DependencyBlock {
  /** Dependency name or identifier. */
  name: string;
  source?: string;
  
  /** Ordered arguments passed to the dependency. */
  params: {
    inputType: "static" | "payload" | "previous-step";
    name: string;
    value: {
      data: string | null;
      type: string;
    };
  }[];
  /** location were the dependency  is */
  location: string;
}
export interface ConditionExpressionPart {
  source: "static" | "dependencies" | "payload" | "operationBlock";
  blockIndex?: number;
  value: string | number | (string | number)[];
  dependencyLocation?:string
  valueType?:
    | "null"
    | "string"
    | "int"
    | "list"
    | "bool"
    | "map"
    | "any"
    | "list (string)"
    | "list (int)";
}

export type OperationBlockData =
  | { type: "database"; databaseBlock: DatabaseOperations }
  | { type: "dependency"; dependenceBlock: DependencyBlock }
  | { type: "apiResponse"; apiResponse: ApiResponse };

/**
 * a block in the operation tree that can be conditionally executed based on a condition gate
 * making all data under it require a condition to be executed
 */
export interface OperationBlock {
    condition: ConditionGate | null;
  /**
   * contains the data for the block, can be a database operation, a dependency call, or an API response
   * the type of the block is determined by the type of the data
   * if the type is database, then the block is a database operation
   * if the type is dependency, then the block is a dependency call
   * if the type is apiResponse, then the block is an API response
   *
   * this allows for a flexible and extensible operation tree that can be used to build complex API routes
   * with multiple steps and dependencies
   * if condition is null, then the block is always executed, otherwise it is executed only if the condition is met
   */
  data: OperationBlockData[];
}

export interface ConditionGate {
  type: string;
  disableCondition: boolean;
  data: ConditionExpression[];
}

export interface ConditionExpression {
  left: ConditionExpressionPart | null;
  operator: string;
  right: ConditionExpressionPart | null;
  joinClause?: "AND" | "OR";
}

/**
 * A generated API route entry with a path, method, and associated payload/operations.
 */
export interface Routes {
  /** HTTP method used by the route. */
  method: HTTPMethods | HTTPMethodsLower;
  /** Route path  the  full path /api/auth/users/login. */
  path: string;
  /** Route name used for example . login */
  name: string;
  /** Optional request/response payload and operation tree for this route. */
  data?: {
    /** Data payload schema for the route. */
    payload: Payload[];
    /** Ordered operation steps defining the route logic. */
    operations: OperationBlock[];
  };
}

/**
 * Lowercase HTTP method strings for convenience where lowercase values are needed.
 */
export type HTTPMethodsLower = Lowercase<HTTPMethods>;

/**
 * A tree node representing a grouped endpoint prefix and its child routes.
 */
export interface EndPointList {
  /** Prefix shared by this group of endpoints. */
  prefix: string;
  /** Whether this endpoint group is currently collapsed in UI. */
  collapsed?: boolean;
  /** Child routes or nested endpoint groups underneath this prefix. */
  children: (Routes | EndPointList)[];
}

export function normalizeEndpointSegments(value: string): string[] {
  const trimmed = (value ?? "").trim().replace(/\s+/g, "-");

  if (!trimmed) {
    return [];
  }

  return trimmed
    .replace(/^\/+|\/+$/g, "")
    .split(/\//)
    .map((segment) => segment.trim().replace(/\s+/g, "-").toLowerCase())
    .filter(Boolean);
}

export function findNestedEndpoint(
  parent: EndPointList,
  segments: string[],
): EndPointList | null {
  let current = parent;

  for (const segment of segments) {
    const child = current.children.find(
      (candidate): candidate is EndPointList =>
        !!candidate &&
        typeof candidate === "object" &&
        "prefix" in candidate &&
        (candidate as EndPointList).prefix.trim().toLowerCase() ===
          segment.trim().toLowerCase(),
    ) as EndPointList | undefined;

    if (!child) {
      return null;
    }

    current = child;
  }

  return current;
}

export function ensureNestedEndpoint(
  parent: EndPointList,
  segments: string[],
): EndPointList {
  let current = parent;

  for (const rawSegment of segments) {
    const segment = rawSegment.trim().replace(/\s+/g, "-").toLowerCase();
    if (!segment) {
      continue;
    }

    const child = current.children.find(
      (candidate): candidate is EndPointList =>
        !!candidate &&
        typeof candidate === "object" &&
        "prefix" in candidate &&
        (candidate as EndPointList).prefix.trim().toLowerCase() === segment,
    ) as EndPointList | undefined;

    if (child) {
      current = child;
      continue;
    }

    const newEndpoint: EndPointList = {
      prefix: segment,
      collapsed: true,
      children: [],
    };

    current.children.push(newEndpoint);
    current = newEndpoint;
  }

  return current;
}

/**
 * Join metadata used to combine tables in a database query.
 */
export interface Join {
  /** Kind of join performed between tables. */
  joinType: "INNER" | "LEFT" | "RIGHT" | "FULL";
  /** Join predicates that describe how the tables connect. */
  conditions: {
    /** Comparison operator used in the join predicate. */
    operator: string;
    /** Logical connector such as AND/OR for the next condition. */
    logical?: string;
    /** Left table name in the condition. */
    leftTable: string;
    /** Left column name in the condition. */
    leftColumn: string;
    /** Right-hand value in the join. */
    right: {
      /** Where the right-side value comes from. */
      source: "column" | "payload" | "static" | "computed";
      /** Table name for column-based comparisons. */
      rightTable: string;
      /** Column name for column-based comparisons. */
      rightColumn: string;
      /** Literal value when the right side is a static or computed value. */
      value?: string | number;
    };
  }[];
}

export const useAppContextStore = defineStore("appContext", {
  state: () => ({
    currentProject: null as string | null,
    currentRoute: "/",
    isInspectorOpen: true,
    isExplorerOpen: true,
    activeLeftPanel: "projects",
    openedTabs: [] as WorkspaceTab[],
    activeTabId: null as string | null,
    activeConnectionName: null as string | null,
    databaseSchemas: {} as Record<string, io.IntermediateSchema>,
    apiSchema: [] as EndPointList[],
    installedDependencies: [] as io.Dependence[],
    projectDependencies: [] as io.Dependence[],
    tabState: {} as Record<string, any>,
    activePlugins: {
      api: null as { port: string; plugin: io.PluginManifestSchema } | null,
      database: null as {
        port: string;
        plugin: io.PluginManifestSchema;
      } | null,
    },
    databaseAttributes: [] as DatabaseAttribute[],
  }),
  getters: {
    activeTab: (state) =>
      state.openedTabs.find((tab) => tab.id === state.activeTabId) || null,
    activeSchema: (state) =>
      state.activeConnectionName
        ? state.databaseSchemas[state.activeConnectionName]
        : null,
  },
  actions: {
    async getInstalledDependencies() {
      this.installedDependencies = await GetAllInstalledDependencies();
    },
    async getProjectDependencies() {
      if (this.currentProject == null) {
        throw Error("no project is found select project first ");
      }
      this.installedDependencies = await GetProjectUsedDependencies(
        this.currentProject,
      );
    },

    async createNewTable(name: string) {
      const emptyField: io.Field = {
        isPrimaryKey: true,
        name: "",
        type: "string" as FieldType,
        length: 0,
        nullish: false,
        attributes: "-",
        autoGen: true,
        default: "-",
      } as io.Field;

      const newTable = {
        name: name,
        fields: [emptyField],
        primaryKey: [],
        description: "",
      } as unknown as io.Entity;
      if (
        this.activeConnectionName &&
        this.databaseSchemas[this.activeConnectionName]
      ) {
        this.databaseSchemas[this.activeConnectionName]["schema"].entities.push(
          newTable,
        );
        return;
      }

      this.databaseSchemas[this.activeConnectionName!] = {
        meta: {
          database: {
            name: "none",
            from: "none",
          },
          version: "",
          description: "",
        } as io.Meta,

        schema: {
          entities: [newTable],
          relationships: [],
        } as unknown as io.Schema,
      } as io.IntermediateSchema;
      SaveProjectSchema(this.currentProject!, this.databaseSchemas);
    },

    async getProjectSchema() {
      if (this.currentProject) {
        this.databaseSchemas = await GetProjectSchema(this.currentProject);
      }
    },
    setCurrentProject(projectName: string | null) {
      this.currentProject = projectName;
      this.getProjectSchema();
    },
    setCurrentRoute(route: string) {
      this.currentRoute = route;
    },
    toggleInspector() {
      this.isInspectorOpen = !this.isInspectorOpen;
    },
    toggleExplorer() {
      this.isExplorerOpen = !this.isExplorerOpen;
    },
    openTab(tab: WorkspaceTab) {
      const exists = this.openedTabs.find((t) => t.id === tab.id);
      if (!exists) {
        this.openedTabs.push(tab);
      }
      this.activeTabId = tab.id;
    },

    createNewTab(
      path: string,
      label: string,
      icon: string,
      query: LocationQuery = {},
      state?: any,
    ) {
      const exists = this.openedTabs.find((t) => t.path === path);
      if (exists) {
        this.activeTabId = exists.id;
        return;
      }
      const id = `id-${this.openedTabs.length.toString()}`;
      this.openedTabs.push({
        id: id,
        label: label,
        path: path,
        icon: icon,
        query: query,
      });
      this.activeTabId = id;

      router.push({ path, force: true, query });
      if (state) {
        this.tabState[path] = state;
      }

      //
    },
    async updateTab(path: string, newTab: { path: string; label: string }) {
      const tab = this.openedTabs.find((v) => v.path === path);
      if (tab) {
        tab.label = newTab.label;
        tab.path = newTab.path;
      }
    },
    getTabByPath(path: string) {
      const tab = this.openedTabs.find((v) => v.path.includes(path));
      return tab;
    },
    closeTab(tabId: string) {
      const index = this.openedTabs.findIndex((t) => t.id === tabId);
      if (index !== -1) {
        const closedTab = this.openedTabs.splice(index, 1);
        delete this.tabState[closedTab[0].path];
        if (this.activeTabId === tabId) {
          if (this.openedTabs.length > 0) {
            // Select the neighboring tab
            const nextTab = this.openedTabs[Math.max(0, index - 1)];
            this.activeTabId = nextTab.id;
            router.push(nextTab.path || "/");
          } else {
            this.activeTabId = null;
            router.push("/");
          }
        }
      }
    },
    setActiveTab(tabId: string) {
      this.activeTabId = tabId;
    },
    setActiveConnection(connectionName: string | null) {
      this.activeConnectionName = connectionName;
    },
    setDatabaseSchema(connectionName: string, schema: io.IntermediateSchema) {
      this.databaseSchemas[connectionName] = schema;
    },
    saveApi() {
      SaveApiSchema(
        JSON.stringify(toRaw(this.apiSchema)),
        this.currentProject!,
      );
    },

    async getApiSchema() {
      const api = await GetApiSchema(this.currentProject!);
      this.apiSchema = api;
    },
    getEndPoint(levels: number[]): EndPointList | null {
      let data: EndPointList | null = null;
      const loopthrough = (i: number, routes: EndPointList) => {
        return routes.children[i];
      };
      for (const level of levels) {
        data = this.apiSchema[level];
        if (levels.length > 1) {
          data = loopthrough(level, data) as EndPointList;
        }
      }

      return data;
    },
    deleteEndPont(levels: number[]) {
      if (levels.length === 1) {
        this.apiSchema[levels[0]].children.forEach((v) => {});
        this.apiSchema.splice(levels[0], 1);
      } else {
        let data = this.apiSchema[0].children;
        for (let index = 1; index < levels.length; index++) {
          const i = levels[index];
          if (index >= levels.length - 1) {
            break;
          }
          data = (data[i] as EndPointList).children;
        }
      }
      this.saveApi();
    },
  },
});
