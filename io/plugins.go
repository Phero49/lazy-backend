// PluginManifestSchema represents the expected structure of a plugin's manifest.json
type PluginManifestSchema struct {
	Version           string            `json:"version"`
	Publisher         string            `json:"publisher"`
	Description       string            `json:"description"`
	Type              string            `json:"type"` //database | api
	Start             string            `json:"start"`
	Stack             Stack             `json:"stack"`
	Run               string            `json:"run"`
	DatabaseEndPoints DatabaseEndPoints `json:"end-points"`
}

type Stack struct {
	Database  string  `json:"database"`
	Framework *string `json:"framework"`
	Language  *string `json:"language"`
}
type EndPointData struct {
	Method string `json:"method"`
	Route  string `json:"route"`
}

type DatabaseEndPoints struct {
	Attributes     EndPointData `json:"attributes"`
	ImportDatabase EndPointData `json:"import-database"`
	Compile        EndPointData `json:"compile"`
}

// PluginItem represents the data stored in the global plugins list
type PluginItem struct {
	Name        string `json:"name"`
	Version     string `json:"version"`
	Publisher   string `json:"publisher"`
	Description string `json:"description"`
	Path        string `json:"path"`
	IsLocal     bool   `json:"is_local"`
	Run         string `json:"run"`
}

type AttributeParam struct {
	Name        string `json:"name"`
	Value       string `json:"value"` // "string", "int", or "float"
	Description string `json:"description,omitempty"`
}

type DatabaseAttribute struct {
	Name        string           `json:"name"`
	Description string           `json:"description"`
	Type        string           `json:"type"` // "property" or "function"
	Params      []AttributeParam `json:"params,omitempty"`
} 
 
type DatabaseAttributes []DatabaseAttribute

func InstallPlugin(pluginPath string, isLocal bool) error {
	cleanPath := filepath.Clean(pluginPath)
	folderName := filepath.Base(cleanPath)
	if folderName == "" || folderName == "." || folderName == ".." {
		return errors.New("invalid plugin path: could not determine folder name")
	}

	// Read and parse the manifest
	manifestPath := path.Join(cleanPath, "manifest.json")
	data, err := os.ReadFile(manifestPath)
	if err != nil {
		return fmt.Errorf("failed to read manifest at %s: %w", manifestPath, err)
	}

	var manifest PluginManifestSchema
	if err := json.Unmarshal(data, &manifest); err != nil {
		return fmt.Errorf("failed to parse manifest JSON: %w", err)
	}

	// Validate SemVer — normalizes and rejects invalid versions
	semver, err := version.NewSemver(manifest.Version)
	if err != nil {
		return fmt.Errorf("invalid manifest version '%s': must be valid SemVer (e.g., 1.0.0, 2.1.3-beta): %w", manifest.Version, err)
	}

	// Use the normalized/canonical form for storage (strips leading zeros, etc.)
	normalizedVersion := semver.String()

	autoGeneratedName := fmt.Sprintf("%s@%s", folderName, normalizedVersion)

	newPlugin := PluginItem{
		Name:        autoGeneratedName,
		Version:     normalizedVersion,
		Publisher:   manifest.Publisher,
		Description: manifest.Description,
		Path:        cleanPath,
		IsLocal:     isLocal,
		Run:         manifest.Run,
	}

	// Load existing plugins list
	pluginsFilePath := path.Join(APP_FOLDER, "plugins.json")
	var plugins []PluginItem

	existingData, err := os.ReadFile(pluginsFilePath)
	if err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("failed to read plugins list: %w", err)
	}

	if len(existingData) > 0 {
		if err := json.Unmarshal(existingData, &plugins); err != nil {
			return fmt.Errorf("failed to parse existing plugins list: %w", err)
		}
	}

	found := false
	for i, p := range plugins {
		if p.Name == newPlugin.Name {
			plugins[i] = newPlugin
			found = true
			break
		}
	}
	if !found {
		plugins = append(plugins, newPlugin)
	}

	if err := os.MkdirAll(APP_FOLDER, 0755); err != nil {
		return fmt.Errorf("failed to create app data directory: %w", err)
	}

	output, err := json.MarshalIndent(plugins, "", "  ")
	if err != nil {
		return fmt.Errorf("failed to marshal plugins list: %w", err)
	}

	if err := os.WriteFile(pluginsFilePath, output, 0644); err != nil {
		return fmt.Errorf("failed to write plugins list: %w", err)
	}

	return nil
}

// DeletePlugin removes a plugin entry from plugins.json by its auto-generated name.
// For non-local plugins, the plugin folder on disk is also removed.
// Local plugins only have their registry entry removed; the folder is preserved.
func DeletePlugin(pluginName string) error {
	if pluginName == "" {
		return fmt.Errorf("plugin name cannot be empty")
	}

	pluginsFilePath := path.Join(APP_FOLDER, "plugins.json")

	// Read existing plugins list
	existingData, err := os.ReadFile(pluginsFilePath)
	if err != nil {
		if os.IsNotExist(err) {
			return fmt.Errorf("plugins list not found at %s: nothing to delete", pluginsFilePath)
		}
		return fmt.Errorf("failed to read plugins list: %w", err)
	}

	var plugins []PluginItem
	if len(existingData) > 0 {
		if err := json.Unmarshal(existingData, &plugins); err != nil {
			return fmt.Errorf("failed to parse existing plugins list: %w", err)
		}
	}

	// Find the target plugin and build filtered list
	var target *PluginItem
	filtered := make([]PluginItem, 0, len(plugins))
	for _, p := range plugins {
		if p.Name == pluginName {
			target = &p
			continue
		}
		filtered = append(filtered, p)
	}

	if target == nil {
		return fmt.Errorf("plugin '%s' not found in plugins list", pluginName)
	}

	// Only delete the folder from disk if the plugin is NOT local
	if !target.IsLocal {
		if target.Path != "" {
			if err := os.RemoveAll(target.Path); err != nil {
				return fmt.Errorf("failed to delete plugin folder at %s: %w", target.Path, err)
			}
		}
	}

	// Write the updated list back to disk
	output, err := json.MarshalIndent(filtered, "", "  ")
	if err != nil {
		return fmt.Errorf("failed to marshal updated plugins list: %w", err)
	}

	if err := os.WriteFile(pluginsFilePath, output, 0644); err != nil {
		return fmt.Errorf("failed to write updated plugins list: %w", err)
	}

	return nil
}

// GetPluginsList returns all plugin entries currently registered in plugins.json.
func GetPluginsList() ([]PluginItem, error) {
	pluginsFilePath := path.Join(APP_FOLDER, "plugins.json")

	existingData, err := os.ReadFile(pluginsFilePath)
	if err != nil {
		if os.IsNotExist(err) {
			return []PluginItem{}, nil
		}
		return nil, fmt.Errorf("failed to read plugins list: %w", err)
	}

	var plugins []PluginItem
	if len(existingData) > 0 {
		if err := json.Unmarshal(existingData, &plugins); err != nil {
			return nil, fmt.Errorf("failed to parse plugins list: %w", err)
		}
	}

	return plugins, nil
}

// PluginDetail combines the registry entry with the full manifest data from disk.
type PluginDetail struct {
	Item     PluginItem           `json:"item"`
	Manifest PluginManifestSchema `json:"manifest"`
}

// GetPlugin retrieves a single plugin by its exact name@version identifier and
// reads the full manifest from the plugin's stored path on disk.
func GetPlugin(pluginName string) (*PluginDetail, error) {
	if pluginName == "" {
		return nil, fmt.Errorf("plugin name cannot be empty")
	}

	// Find the matching registry entry
	plugins, err := GetPluginsList()
	if err != nil {
		return nil, err
	}

	var matched *PluginItem
	for i := range plugins {
		if plugins[i].Name == pluginName {
			matched = &plugins[i]
			break
		}
	}

	if matched == nil {
		return nil, fmt.Errorf("plugin '%s' not found in plugins list", pluginName)
	}

	// Read the full manifest from the stored plugin path
	if matched.Path == "" {
		return nil, fmt.Errorf("plugin '%s' has no stored path", pluginName)
	}

	manifestPath := path.Join(matched.Path, "manifest.json")
	data, err := os.ReadFile(manifestPath)
	if err != nil {
		return nil, fmt.Errorf("failed to read manifest for '%s' at %s: %w", pluginName, manifestPath, err)
	}

	var manifest PluginManifestSchema
	if err := json.Unmarshal(data, &manifest); err != nil {
		return nil, fmt.Errorf("failed to parse manifest for '%s': %w", pluginName, err)
	}

	return &PluginDetail{
		Item:     *matched,
		Manifest: manifest,
	}, nil
}

// LoadLocalPlugin opens a native directory picker via Wails, validates the selected
// folder contains a valid plugin manifest, and registers it as a local plugin.
// Local plugins are never deleted from disk on uninstall.
func LoadLocalPlugin(ctx context.Context) error {
	folder, err := runtime.OpenDirectoryDialog(ctx, runtime.OpenDialogOptions{
		Title:                "Select Plugin Folder",
		CanCreateDirectories: false,
	})
	if err != nil {
		return fmt.Errorf("directory dialog failed: %w", err)
	}

	// User cancelled the dialog
	if folder == "" {
		return nil
	}

	// Register as local — folder will be preserved on delete
	if err := InstallPlugin(folder, true); err != nil {
		return fmt.Errorf("failed to load local plugin from %s: %w", folder, err)
	}

	return nil
}

// AddPluginToProject adds a plugin (by its exact name@version identifier) to the
// project's active-plugins.json. Only the name reference is stored; full details
// are resolved from the global plugins list at read time.
func AddPluginToProject(projectName string, pluginName string) error {
	if projectName == "" {
		return fmt.Errorf("project name cannot be empty")
	}
	if pluginName == "" {
		return fmt.Errorf("plugin name cannot be empty")
	}

	// Resolve and validate the project directory
	projectDir, err := GetProjectDir()
	if err != nil {
		return fmt.Errorf("failed to get project directory: %w", err)
	}
	projectPath := path.Join(projectDir, projectName)

	info, err := os.Stat(projectPath)
	if err != nil || !info.IsDir() {
		return fmt.Errorf("project '%s' does not exist at %s", projectName, projectPath)
	}

	// Validate the plugin exists in the global registry
	plugins, err := GetPluginsList()
	if err != nil {
		return fmt.Errorf("failed to read global plugins list: %w", err)
	}

	found := false
	for _, p := range plugins {
		if p.Name == pluginName {
			found = true
			break
		}
	}
	if !found {
		return fmt.Errorf("plugin '%s' is not installed; run InstallPlugin or LoadLocalPlugin first", pluginName)
	}

	// Read existing active-plugins.json
	activeFilePath := path.Join(projectPath, "active-plugins.json")
	var activeNames []string

	existingData, err := os.ReadFile(activeFilePath)
	if err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("failed to read active-plugins.json: %w", err)
	}

	if len(existingData) > 0 {
		if err := json.Unmarshal(existingData, &activeNames); err != nil {
			return fmt.Errorf("failed to parse active-plugins.json: %w", err)
		}
	}

	// Idempotent: skip if already present
	for _, name := range activeNames {
		if name == pluginName {
			return nil
		}
	}

	// Append and write back
	activeNames = append(activeNames, pluginName)

	output, err := json.MarshalIndent(activeNames, "", "  ")
	if err != nil {
		return fmt.Errorf("failed to marshal active-plugins.json: %w", err)
	}

	if err := os.WriteFile(activeFilePath, output, 0644); err != nil {
		return fmt.Errorf("failed to write active-plugins.json: %w", err)
	}

	return nil
}

// GetActivePlugins returns full PluginItem details for all plugins activated in
// the given project. Names are read from active-plugins.json and resolved against
// the global plugins list. Entries referencing uninstalled plugins are silently skipped.
func GetActivePlugins(projectName string) ([]PluginItem, error) {
	if projectName == "" {
		return nil, fmt.Errorf("project name cannot be empty")
	}

	projectDir, err := GetProjectDir()
	if err != nil {
		return nil, fmt.Errorf("failed to get project directory: %w", err)
	}

	activeFilePath := path.Join(projectDir, projectName, "active-plugins.json")
	data, err := os.ReadFile(activeFilePath)
	if err != nil {
		if os.IsNotExist(err) {
			return []PluginItem{}, nil
		}
		return nil, fmt.Errorf("failed to read active-plugins.json: %w", err)
	}

	var activeNames []string
	if err := json.Unmarshal(data, &activeNames); err != nil {
		return nil, fmt.Errorf("failed to parse active-plugins.json: %w", err)
	}

	// Build a lookup map from the global list for O(1) resolution
	allPlugins, err := GetPluginsList()
	if err != nil {
		return nil, fmt.Errorf("failed to read global plugins list: %w", err)
	}

	pluginMap := make(map[string]PluginItem, len(allPlugins))
	for _, p := range allPlugins {
		pluginMap[p.Name] = p
	}

	// Resolve names to full items, skipping any that are no longer installed
	resolved := make([]PluginItem, 0, len(activeNames))
	for _, name := range activeNames {
		if item, ok := pluginMap[name]; ok {
			resolved = append(resolved, item)
		}
	}

	return resolved, nil
}

// RemovePluginFromProject removes a plugin (by its exact name@version identifier)
// from the project's active-plugins.json. This only removes the reference; the
// plugin remains installed globally and the plugin folder is never deleted.
func RemovePluginFromProject(projectName string, pluginName string) error {
	if projectName == "" {
		return fmt.Errorf("project name cannot be empty")
	}
	if pluginName == "" {
		return fmt.Errorf("plugin name cannot be empty")
	}

	// Resolve and validate the project directory
	projectDir, err := GetProjectDir()
	if err != nil {
		return fmt.Errorf("failed to get project directory: %w", err)
	}
	projectPath := path.Join(projectDir, projectName)

	info, err := os.Stat(projectPath)
	if err != nil || !info.IsDir() {
		return fmt.Errorf("project '%s' does not exist at %s", projectName, projectPath)
	}

	// Read existing active-plugins.json
	activeFilePath := path.Join(projectPath, "active-plugins.json")
	var activeNames []string

	existingData, err := os.ReadFile(activeFilePath)
	if err != nil {
		if os.IsNotExist(err) {
			return fmt.Errorf("plugin '%s' is not active in project '%s': no active-plugins.json found", pluginName, projectName)
		}
		return fmt.Errorf("failed to read active-plugins.json: %w", err)
	}

	if len(existingData) > 0 {
		if err := json.Unmarshal(existingData, &activeNames); err != nil {
			return fmt.Errorf("failed to parse active-plugins.json: %w", err)
		}
	}

	// Filter out the target plugin
	found := false
	filtered := make([]string, 0, len(activeNames))
	for _, name := range activeNames {
		if name == pluginName {
			found = true
			continue
		}
		filtered = append(filtered, name)
	}

	if !found {
		return fmt.Errorf("plugin '%s' is not active in project '%s'", pluginName, projectName)
	}

	// Write the updated list back
	output, err := json.MarshalIndent(filtered, "", "  ")
	if err != nil {
		return fmt.Errorf("failed to marshal active-plugins.json: %w", err)
	}

	if err := os.WriteFile(activeFilePath, output, 0644); err != nil {
		return fmt.Errorf("failed to write active-plugins.json: %w", err)
	}

	return nil
}
